import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { loadDelegationConfig, resolveRoute } from './delegation-config.mjs';
import { nativeAgentName } from './roles.mjs';
import { generateJobId } from './state.mjs';

const BEGIN = '<!-- agent-delegation:start -->';
const END = '<!-- agent-delegation:end -->';
const GENERATED = '# Generated by agent-delegation configure. Edit .agent-delegation.json and configure again.\n';
const hash = text => createHash('sha256').update(text).digest('hex');

export function defaultConfiguration(host) {
  return {
    orchestrator: { host },
    automation: { mode: 'auto', maxParallel: 4 },
    supervisor: { maxIterations: 4, maxWorkers: 2, plannerRole: 'planner', executorRole: 'executor', reviewerRole: 'reviewer', verifyCommands: [] },
    defaultExecutor: 'agy',
    executors: {},
    roles: {
      planner: { executor: host, transport: 'auto', purpose: 'planner' },
      advisor: { executor: host, transport: 'auto', purpose: 'advisor' },
      executor: { executor: 'agy', purpose: 'executor' },
      reviewer: { executor: host, transport: 'auto', purpose: 'reviewer' },
    },
  };
}

export function instructionBlock(host, configPath, orchestratorInstructions = '') {
  const extra = orchestratorInstructions ? `\nConfigured orchestrator instructions: ${orchestratorInstructions}` : '';
  return `${BEGIN}\nFor coding implementation, debugging, and change review, use the agent-delegation plugin's delegate skill to apply the roles in ${JSON.stringify(configPath)}. Read automation.mode before delegating: auto permits useful bounded delegation; manual requires an explicit delegation request. Small tasks can stay in the parent. User task instructions take precedence over this workflow.\nUse native agents only when the configured route selects this host (${host}); use the plugin's CLI runner for other harnesses. The parent owns integration and acceptance checks. Acting as a delegated worker, or with AGENT_DELEGATION_WORKER=1, complete the assigned task directly without invoking this orchestration workflow. If the plugin is unavailable, report that and continue the authorized task with available host capabilities.${extra}\n${END}`;
}

function replaceBlock(text, block) {
  const begin = text.indexOf(BEGIN), end = text.indexOf(END);
  if (begin < 0 && end < 0) return text + (text && !text.endsWith('\n') ? '\n' : '') + (text ? '\n' : '') + block + '\n';
  if (begin < 0 || end < begin || text.indexOf(BEGIN, begin + BEGIN.length) >= 0 || text.indexOf(END, end + END.length) >= 0) throw new Error('Malformed agent-delegation instruction markers; repair them before configuring');
  return text.slice(0, begin) + block + text.slice(end + END.length);
}

function safePath(root, name) {
  const path = resolve(root, name);
  const rel = relative(root, path);
  if (!rel || rel === '..' || rel.startsWith(`..${process.platform === 'win32' ? '\\' : '/'}`) || isAbsolute(rel)) throw new Error(`Generated path escapes project: ${name}`);
  let part = root;
  for (const segment of rel.split(/[\\/]/)) {
    part = join(part, segment);
    try {
      if (lstatSync(part).isSymbolicLink()) throw new Error(`Refusing to write through a symlink: ${part}`);
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  return path;
}

export function renderNativeAgent(host, name, route) {
  const contract = route;
  if (host === 'codex') {
    return GENERATED + [
      `name = ${JSON.stringify(nativeAgentName(name))}`,
      `description = ${JSON.stringify(contract.description)}`,
      ...(route.model ? [`model = ${JSON.stringify(route.model)}`] : []),
      ...(route.effort ? [`model_reasoning_effort = ${JSON.stringify(route.effort)}`] : []),
      ...(contract.readOnly ? ['sandbox_mode = "read-only"'] : []),
      `developer_instructions = ${JSON.stringify(contract.instructions)}`,
    ].join('\n') + '\n';
  }
  return ['---', `name: ${nativeAgentName(name)}`, `description: ${JSON.stringify(contract.description)}`,
    ...(route.model ? [`model: ${JSON.stringify(route.model)}`] : []),
    ...(route.effort ? [`effort: ${JSON.stringify(route.effort)}`] : []),
    ...(contract.readOnly ? ['tools: Read, Glob, Grep', 'permissionMode: plan'] : ['disallowedTools: Agent']),
    '---', GENERATED.trim(), '', contract.instructions, ''].join('\n');
}

export function configureProject({ cwd, host, configFile, dryRun = false }) {
  const root = realpathSync(cwd);
  if (!['codex', 'claude'].includes(host)) throw new Error('configure requires --host codex|claude');
  const configPath = resolve(root, configFile ?? '.agent-delegation.json');
  const hasConfig = existsSync(configPath);
  if (!hasConfig && configFile) throw new Error(`Configuration does not exist: ${configPath}`);
  const config = hasConfig ? loadDelegationConfig(root, configFile) : defaultConfiguration(host);
  const ledgerName = `.agent-delegation/generated-${host}.json`;
  const ledgerPath = safePath(root, ledgerName);
  const previous = existsSync(ledgerPath) ? JSON.parse(readFileSync(ledgerPath, 'utf8')) : {};
  const generated = {};
  for (const [name, role] of Object.entries(config.roles)) {
    const route = resolveRoute(config, { role: name, host });
    if (route.transport !== 'native' || route.executor !== host) continue;
    if (role.agent || route.agent) throw new Error(`Native role ${name} cannot use a CLI agent override`);
    const file = `.${host}/agents/${nativeAgentName(name)}.${host === 'codex' ? 'toml' : 'md'}`;
    generated[file] = renderNativeAgent(host, name, route);
  }
  // Verify every owned file before writing anything, including files retired by a route change.
  for (const name of new Set([...Object.keys(previous), ...Object.keys(generated)])) {
    if (!new RegExp(`^\\.${host}/agents/delegation-[a-z][a-z0-9_-]{0,63}\\.${host === 'codex' ? 'toml' : 'md'}$`).test(name)) throw new Error(`Invalid generated-file record: ${name}`);
    const path = safePath(root, name);
    if (existsSync(path)) {
      const text = readFileSync(path, 'utf8');
      if (hash(text) !== previous[name] && text !== generated[name]) throw new Error(`Preserving modified or unowned agent file: ${path}. Move it or restore the generated version before configuring.`);
    }
  }
  const instructionName = host === 'codex' ? 'AGENTS.md' : 'CLAUDE.md';
  const instructionPath = safePath(root, instructionName);
  const priorInstructions = existsSync(instructionPath) ? readFileSync(instructionPath, 'utf8') : '';
  const reference = relative(root, configPath).replaceAll('\\', '/');
  const instructions = replaceBlock(priorInstructions, instructionBlock(host, reference, config.orchestrator?.instructions));
  const writes = { ...generated, [instructionName]: instructions, [ledgerName]: JSON.stringify(Object.fromEntries(Object.entries(generated).map(([name, value]) => [name, hash(value)])), null, 2) + '\n' };
  if (!hasConfig) writes['.agent-delegation.json'] = JSON.stringify(config, null, 2) + '\n';
  for (const name of Object.keys(writes)) safePath(root, name);
  const removed = Object.keys(previous).filter(name => !(name in generated) && existsSync(safePath(root, name)));
  if (!dryRun) {
    for (const [name, value] of Object.entries(writes)) {
      const path = safePath(root, name);
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, value, 'utf8');
    }
    for (const name of removed) unlinkSync(safePath(root, name));
  }
  return { host, configPath, dryRun, written: Object.keys(writes), removed, note: 'Install the agent-delegation plugin in this host. Start a new session to load native agents and instructions.' };
}

export function launchSpec(config, host = config.orchestrator?.host) {
  if (!['codex', 'claude'].includes(host)) throw new Error('Set orchestrator.host or pass --host codex|claude');
  const parent = config.orchestrator ?? {};
  // Model IDs and effort preferences belong to their configured host.
  if (parent.host && parent.host !== host) throw new Error(`Orchestrator is configured for ${parent.host}; update it before launching ${host}`);
  const args = [];
  if (parent.model) args.push('--model', parent.model);
  if (host === 'codex') {
    if (parent.effort) args.push('-c', `model_reasoning_effort=${JSON.stringify(parent.effort)}`);
    args.push('-c', 'agents.enabled=true', '-c', `agents.max_concurrent_threads_per_session=${config.automation?.maxParallel ?? 4}`);
  } else if (parent.effort) args.push('--effort', parent.effort);
  return { binary: host, args };
}

export async function launchHost(spec, { cwd, env = process.env } = {}) {
  return new Promise((resolveExit, reject) => {
    const child = spawn(env[`${spec.binary.toUpperCase()}_BINARY`] ?? spec.binary, spec.args, { cwd, env: { ...env, AGENT_SESSION_ID: env.AGENT_SESSION_ID ?? generateJobId('parent') }, stdio: 'inherit', shell: false, windowsHide: false });
    const ignoreInterrupt = () => {}; // The interactive host receives the terminal's interrupt too.
    process.on('SIGINT', ignoreInterrupt);
    const cleanup = () => process.removeListener('SIGINT', ignoreInterrupt);
    child.once('error', err => { cleanup(); reject(err); });
    child.once('exit', (code) => { cleanup(); resolveExit(code ?? 1); });
  });
}
